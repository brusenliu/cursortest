export function baseParams(overrides = {}) {
  return {
    arrangement: 'staggered',
    spacing: 28,
    width: 800,
    height: 600,
    angle: 0,
    sizeMode: 'fixed',
    size: 8,
    sizeStart: 2,
    sizeEnd: 12,
    linearAngle: 0,
    radialCenter: { x: 0.5, y: 0.5 },
    radialRadius: 340,
    sizeMin: 3,
    sizeMax: 12,
    maskMin: 0,
    maskMax: 14,
    maskSource: 'star',
    shape: 'circle',
    strokeWidth: 2.5,
    starPoints: 5,
    ellipseRatio: 0.62,
    colorMode: 'single',
    dotColor: '#1a1a1a',
    transparent: true,
    backgroundColor: '#fff6ee',
    palette: [...PALETTE],
    edgeFade: false,
    fadeWidth: 140,
    noise: false,
    noiseDelete: 0.2,
    noiseJitter: 0.35,
    invert: false,
    merge: true,
    seed: 1,
    ...overrides,
    radialCenter: { x: 0.5, y: 0.5, ...(overrides.radialCenter || {}) },
    palette: overrides.palette ? [...overrides.palette] : [...PALETTE],
  }
}

export function cloneParams(params) {
  return {
    ...params,
    radialCenter: { ...params.radialCenter },
    palette: [...params.palette],
  }
}

function preset(id, name, overrides) {
  return { id, name, params: baseParams(overrides) }
}

